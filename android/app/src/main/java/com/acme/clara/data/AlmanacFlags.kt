    // These cards deliberately use a regional flag rather than the sovereign-state flag.
    private val placeOverrides: Map<String, String> = mapOf(
        "Edinburgh" to "gb-sct",
        "Hong Kong" to "hk",
        "Scottish Highlands" to "gb-sct",
    )

    /** Stable country/territory key shared by every destination shown under the same flag. */
    fun countryCode(place: String): String? =
        expansionCountries[place]
            ?: placeOverrides[place]
            ?: CountryShapes.placeCountry[place]?.let(alpha3ToAlpha2::get)

    fun assetName(place: String): String? = countryCode(place)?.let { "flag_$it" }
